"""Collects Gen AI lab rounds from the app's history for the knowledge base.

    python3 scripts/kb-gen-samples.py

Reads rounds from VTracer's Gen AI history on this machine, renders each
trace to a small preview, and writes the previews with a samples.json of
their facts (model, settings, path count, SVG size) into
scripts/kb-sources/gen-ai/. scripts/kb-diagrams.py draws the figures from
there, so the figures can be redrawn without the app's history. Needs resvg.
"""
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "scripts/kb-sources/gen-ai")
GEN = os.path.expanduser("~/Library/Application Support/org.visioncortex.vtracer/vt2/gen")
HISTORIES = ["history", "history.bak", "history.dogs"]
PREVIEW = 480  # pixels; figures show them at 240 or smaller

MODELS = ["sd-turbo-q8", "sdxl-turbo-q8", "flux-schnell-q4", "flux2-klein-4b-q4", "z-image-turbo-q4"]

# One prompt, run on each local model: (sample name, model) -> round id prefix.
COMPARE = {
    "chibi-sticker": ["01a0ecba-36a7", "01a0ecbf-6be4", "01a0ecda-55d5", "01a0ecc8-0a62", "01a0eccf-8181"],
    "comic-1950s": ["01a0ecbc-90b0", "01a0ecc5-8376", "01a0ece2-4806", "01a0eccb-d7dd", "01a0ecd5-f37d"],
    "manga-ink": ["01a0ecbb-b88e", "01a0ecc2-b31a", "01a0ecdf-31aa", "01a0ecca-1efc", "01a0ecd3-041a"],
    "anime-portrait": ["01a0ecb9-6a59", "01a0ecbd-7c21", "01a0ecd7-d727", "01a0ecc6-a50d", "01a0eccd-2761"],
    "shoujo-manga": ["01a0ecba-96e0", "01a0ecc0-43aa", "01a0ecdb-9189", "01a0ecc8-b8dc", "01a0ecd0-a9ba"],
    "vintage-anime": ["01a0ecbc-3279", "01a0ecc4-69fc", "01a0ece1-10dc", "01a0eccb-27dc", "01a0ecd4-c7be"],
}

# The fox sketch, generated by Z-Image Turbo at rising strength.
STRENGTH = ["01a0e469-cee6", "01a0e473-e0dc", "01a0e46a-7556", "01a0e46b-2333"]

# OpenAI Codex: a red fox sitting in eight art styles, one round in Cartoon
# kept with its generated image, and two rounds from the fox sketch.
CODEX_STYLES = {
    "inked": "01a0b58c-3ee9",
    "flat-design": "01a0b58c-fcb8",
    "clipart": "01a0b58d-c29d",
    "cartoon": "01a0b58e-83a6",
    "stencil": "01a0b58f-3f12",
    "low-poly": "01a0b58f-f0a0",
    "linocut": "01a0b590-cde4",
    "line-art": "01a0b591-ab26",
}
CODEX_ROUND = "01a0b598-403d"

# The Stable Diffusion galleries: good rounds of simple subjects, not the
# anime test set, which plays to the newer models' prompt following.
GALLERY = {
    # Z-Image Turbo across anime styles: chibi, shoujo, shonen ink, retro anime.
    "z-image-turbo-q4": ["01a0ecce-56cb", "01a0ecd0-a9ba", "01a0ecd1-d859", "01a0ecd4-c7be"],
    "sd-turbo-q8": ["01a11b7e-16ca"],
    "flux-schnell-q4": ["01a11c8d-1298", "01a087b8-de94", "01a08820-3996"],
}
CODEX_SKETCH = {"line-art": "01a0fbf1-911a", "plain": "01a0fbf0-67e1"}  # the three cats, as a reference

# Line art from the three cats sketch (strength 0.3; the article does not name the model).
PENCIL_CATS = "01a0dea7-6dab"


def find(prefix):
    for hist in HISTORIES:
        h = os.path.join(GEN, hist)
        for name in os.listdir(h):
            if name.startswith(prefix):
                return os.path.join(h, name)
    raise SystemExit(f"round {prefix} is not in the history")


# Galleries made from a saved SVG rather than a history round: model -> file
# under scripts/kb-sources/images/.
GALLERY_FILES = {
    "flux2-klein-4b-q4": [
        "flux-vector-art/flux-2-klein-fox.svg",
        # The smiling girl from the mesh gradient article: the 1990s shoujo
        # test prompt (round 01a0ecc9-145a), traced with mesh gradients.
        "mesh-gradients/anime-girl-smiling.svg",
    ],
}


def collect_file(name, rel):
    """A trace saved from the app: a preview and its facts, as collect() gives."""
    from PIL import Image

    svg_path = os.path.join(ROOT, "scripts/kb-sources/images", rel)
    png = os.path.join(OUT, name + ".png")
    subprocess.run(["resvg", "-w", str(PREVIEW), svg_path, png], check=True)
    Image.open(png).save(os.path.join(OUT, name + ".webp"), quality=85, method=6)
    os.remove(png)
    return {"preview": name + ".webp", "paths": open(svg_path).read().count("<path"), "svg_bytes": os.path.getsize(svg_path)}


def subject_of(prefix):
    pi = json.load(open(os.path.join(find(prefix), "entry.json"))).get("promptInput") or {}
    return ", ".join([pi.get("subject") or ""] + list(pi.get("details") or []))


def collect(name, prefix):
    d = find(prefix)
    entry = json.load(open(os.path.join(d, "entry.json")))
    svg_path = os.path.join(d, "out.svg")
    svg = open(svg_path).read()
    png = os.path.join(OUT, name + ".png")
    subprocess.run(["resvg", "-w", str(PREVIEW), svg_path, png], check=True)
    from PIL import Image  # keep the previews small: WebP with transparency

    Image.open(png).save(os.path.join(OUT, name + ".webp"), quality=85, method=6)
    os.remove(png)
    p = entry.get("params", {})
    return {
        "preview": name + ".webp",
        "model": entry.get("modelId"),
        "prompt": (entry.get("promptInput") or {}).get("description") or entry.get("prompt"),
        "style": (entry.get("style") or {}).get("id"),
        "seed": entry.get("seed"),
        "steps": p.get("steps"),
        "cfg": p.get("cfgScale"),
        "size": [p.get("width"), p.get("height")],
        "image": [(entry.get("image") or {}).get("width"), (entry.get("image") or {}).get("height")],
        "strength": (entry.get("sketch") or {}).get("strength"),
        "paths": svg.count("<path"),
        "svg_bytes": os.path.getsize(svg_path),
        "seconds": (entry.get("completedAt") or 0) - (entry.get("createdAt") or 0),
    }


def main():
    os.makedirs(OUT, exist_ok=True)
    samples = {"compare": {}, "strength": []}
    for sample, prefixes in COMPARE.items():
        samples["compare"][sample] = {m: collect(f"{sample}-{m}", p) for m, p in zip(MODELS, prefixes)}
    for prefix in STRENGTH:
        s = collect(f"fox-sketch-{prefix[:8]}", prefix)
        s["preview"] = f"fox-sketch-{s['strength']}.webp"
        os.replace(os.path.join(OUT, f"fox-sketch-{prefix[:8]}.webp"), os.path.join(OUT, s["preview"]))
        samples["strength"].append(s)
    samples["codex"] = {
        "styles": {k: collect(f"codex-{k}", p) for k, p in CODEX_STYLES.items()},
        "round": collect("codex-round", CODEX_ROUND),
        "sketch": {k: collect(f"codex-sketch-{k}", p) for k, p in CODEX_SKETCH.items()},
    }
    samples["pencil_cats"] = collect("pencil-cats-line-art", PENCIL_CATS)
    samples["gallery"] = {
        m: [dict(collect(f"gallery-{m}-{k}", p), subject=subject_of(p)) for k, p in enumerate(ids)] for m, ids in GALLERY.items()
    }
    for m, files in GALLERY_FILES.items():
        samples["gallery"][m] = [collect_file(f"gallery-{m}-{k}", rel) for k, rel in enumerate(files)]
    # The image Codex generated for the round, before tracing, kept small.
    from PIL import Image

    im = Image.open(os.path.join(find(CODEX_ROUND), "source.webp")).convert("RGB")
    im.thumbnail((PREVIEW, PREVIEW), Image.LANCZOS)
    im.save(os.path.join(OUT, "codex-round-generated.webp"), quality=85, method=6)
    with open(os.path.join(OUT, "samples.json"), "w") as fh:
        json.dump(samples, fh, indent=1)
    print("wrote", OUT)


main()
